            var directions = new int[][] { new int[] { 0, 1 }, new int[] { 1, 0 }, new int[] { 0, -1 }, new int[] { -1, 0 }, new int[] { 1, 1 }, new int[] { -1, -1 }, new int[] { -1, 1 }, new int[] { 1, -1 } };
            var pq = new PriorityQueue<(int x, int y), int>();
            pq.Enqueue((0, 0), 1);
            var visited = new HashSet<(int x, int y)>();
            visited.Add((0, 0));
            while (pq.Count > 0)
            {
                var (x, y) = pq.Dequeue();
                if (x == n - 1 && y == n - 1) return grid[x][y];
                foreach (var dir in directions)
                {
                    int nx = x + dir[0];
                    int ny = y + dir[1];
                    if (nx >= 0 && nx < n && ny >= 0 && ny < n && grid[nx][ny] == 0 && !visited.Contains((nx, ny)))
                    {
                        visited.Add((nx, ny));
                        grid[nx][ny] = grid[x][y] + 1;
                        pq.Enqueue((nx, ny), grid[nx][ny] + Math.Abs(n - 1 - nx) + Math.Abs(n - 1 - ny));
