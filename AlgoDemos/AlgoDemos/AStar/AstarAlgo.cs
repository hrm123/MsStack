            int n = grid.Length;

            // we have to always follow o's path and avoid 1's
            // once we have visited a ndoe, we will not visit it again ,
            // so we can modify the grid to store the distance from the start point (where 0's were there originally)
            if (n == 0 || grid[0][0] != 0 || grid[n - 1][n - 1] != 0) return -1;

            Dictionary<(int, int), int> f_n = new();
            f_n[(0, 0)] = 0; // this cost does not matter since first vertex is dequed first and it will be the only one in the queue when it is dequed


            PriorityQueue<(int x, int y, int steps), int> pq = new();

            pq.Enqueue((0, 0, 1), f_n[(0, 0)]);

            int nx = -1;
            int ny = -1;
            int x, y, steps;
            int new_f_n, existing_f_n;

            while (pq.Count > 0)
            {
                new_f_n = existing_f_n = x = y = steps = nx = ny = -1;
                (x, y, steps) = pq.Dequeue();

                if (x == n - 1 && y == n - 1)
                {
                    return steps; // reached destination node
                }
                for (int i = 0; i < _directions.Length; i++)
                {
                    nx = x + _directions[i][0];
                    ny = y + _directions[i][1];
                    
                    // new node is valid only for valid values of nx & ny, and
                    // if it is not a wall (1) and
                    // if it is not visited before
                    if (nx < 0 || nx >= n || ny < 0 || ny >= n ||
                        grid[nx][ny] != 0
                        )
                    {
                        continue;
                    }

                    new_f_n = steps + 1 + Math.Max(Math.Abs(nx - (n - 1)), Math.Abs(ny - (n - 1))); 
                    if (f_n.TryGetValue((nx, ny), out existing_f_n) && existing_f_n <= new_f_n)
                    {
                        // Console.WriteLine($"skipping one node ({nx}, {ny}) since it is already in the queue with lesser f(n) value");
                        continue; // no need to enqueue this node since it is already in the queue and with lesser cost
                    }
                    f_n[(nx, ny)] = new_f_n;
                    pq.Enqueue((nx, ny, steps + 1), new_f_n); // f(n) = g(n) + h(n) where heuristic is Diagonal distance
                    
                }
            }

            // no path found
            return -1;

        }


