        public double TieBreakerh_n(int x, int y, int goalX, int goalY)
        {
            // Calculate the vector from the start to the goal
            double startToGoalX = goalX - 0; // Assuming start is at (0, 0)
            double startToGoalY = goalY - 0;
            // Calculate the vector from the current point to the goal
            double currentToGoalX = goalX - x;
            double currentToGoalY = goalY - y;
            // Calculate the cross product of the two vectors
            double crossProduct = startToGoalX * currentToGoalY - startToGoalY * currentToGoalX;
            // Return a small value based on the cross product to break ties
            return Math.Abs(crossProduct) * 0.001; // Adjust the multiplier as needed
        }


