            var directions = new int[][] { new int[] { 0, 1 }, new int[] { 1, 0 }, new int[] { 0, -1 }, new int[] { -1, 0 }, new int[] { 1, 1 }, new int[] { -1, -1 }, new int[] { -1, 1 }, new int[] { 1, -1 } };
